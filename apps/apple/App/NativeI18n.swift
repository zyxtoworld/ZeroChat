    private static func resolveLocale(mode: String, preferredLanguages: [String]) -> String {
        if supportedLocales.contains(mode) {
            return mode
        }

        for language in preferredLanguages {
            if let locale = localeFromLanguage(language) {
                return locale
            }
        }

        return "en-US"
    }

    private static func localeFromLanguage(_ language: String) -> String? {
        let value = language.lowercased()
        if value.hasPrefix("zh") { return "zh-CN" }
        if value.hasPrefix("en") { return "en-US" }
        if value.hasPrefix("es") { return "es-ES" }
        if value.hasPrefix("hi") { return "hi-IN" }
        if value.hasPrefix("ar") { return "ar-SA" }
        if value.hasPrefix("pt") { return "pt-BR" }
        if value.hasPrefix("ru") { return "ru-RU" }
        if value.hasPrefix("ja") { return "ja-JP" }
        if value.hasPrefix("ko") { return "ko-KR" }
        if value.hasPrefix("fr") { return "fr-FR" }
        return nil
    }

    private static func afterColon(_ text: String) -> String {
        guard let colon = text.firstIndex(of: ":") else {
            return text
        }
        return String(text[text.index(after: colon)...])
            .trimmingCharacters(in: .whitespacesAndNewlines)
    }

