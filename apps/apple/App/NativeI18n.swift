import Foundation
import ZeroChatCore

struct NativeI18n {
    let locale: String

    init(mode: String, preferredLanguages: [String] = Locale.preferredLanguages) {
        locale = Self.resolveLocale(mode: mode, preferredLanguages: preferredLanguages)
    }

    func t(_ key: String) -> String {
        Self.translations[locale]?[key]
            ?? Self.capabilityTranslations[locale]?[key]
            ?? Self.skillTranslations[locale]?[key]
            ?? Self.providerErrorTranslations[locale]?[key]
            ?? Self.runtimeTranslations[locale]?[key]
            ?? Self.translations["en-US"]?[key]
            ?? Self.capabilityTranslations["en-US"]?[key]
            ?? Self.skillTranslations["en-US"]?[key]
            ?? Self.providerErrorTranslations["en-US"]?[key]
            ?? Self.runtimeTranslations["en-US"]?[key]
            ?? Self.translations["zh-CN"]?[key]
            ?? Self.capabilityTranslations["zh-CN"]?[key]
            ?? Self.skillTranslations["zh-CN"]?[key]
            ?? Self.providerErrorTranslations["zh-CN"]?[key]
            ?? Self.runtimeTranslations["zh-CN"]?[key]
            ?? key
    }

    func formatNumber(_ value: Int) -> String {
        let formatter = NumberFormatter()
        formatter.locale = Locale(identifier: locale)
        formatter.numberStyle = .decimal
        return formatter.string(from: NSNumber(value: value)) ?? "\(value)"
    }

    func isDefaultConversationTitle(_ title: String) -> Bool {
        let trimmed = title.trimmingCharacters(in: .whitespacesAndNewlines)
        return Self.translations.values.contains { dictionary in
            dictionary["title.newChat"] == trimmed
        }
    }

    func errorMessage(_ error: Error) -> String {
        if let compensationError = error as? AppleCompensationError {
            return ([compensationError.operationError] + compensationError.compensationErrors)
                .map(errorMessage)
                .filter { !$0.isEmpty }
                .joined(separator: "\n")
        }
        if let localFileError = error as? LocalFileReadError,
           case .tooLarge(let maxBytes) = localFileError {
            return t("message.fileTooLarge")
                .replacingOccurrences(
                    of: "{maxMb}",
                    with: formatNumber(maxBytes / 1_000_000)
                )
        }
        return errorMessage(error.localizedDescription)
    }

    func errorMessage(_ raw: String) -> String {
        let text = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        if text.isEmpty {
            return ""
        }

        if text == "Local snapshot recovery is required." {
            return t("message.localSnapshotLoadFailed")
        }
        if text == "Local storage is unavailable." {
            return t("message.localStorageUnavailable")
        }
        if text == "Cloudflare access key is required" ||
            text == "Cloudflare access key is required." {
            return t("error.cloudflareAccessKeyRequired")
        }
        if text == "GitHub token is required" ||
            text == "GitHub token is required." {
            return t("error.syncGithubTokenRequired")
        }
        if text == "Could not get a Gist ID" ||
            text == "Could not get a Gist ID." {
            return t("error.syncGistIdMissing")
        }
        if text == "Provider API key is required" ||
            text == "Provider API key is required." ||
            text == "Provider key is required" ||
            text == "Provider key is required." {
            return t("error.providerKeyRequired")
        }
        if text == "Cloudflare already has newer sync data. Use the latest app or clear cloud data before syncing here." {
            return t("error.cloudflareNewerSyncData")
        }
        if text.hasPrefix("Cloudflare has incremental sync data.") {
            return t("error.cloudflareNewerSyncData")
        }
        if text == "Local and cloud both have data. Choose local, cloud, or merge before syncing." {
            return t("error.firstSyncConflict")
        }
        if text == "File format is invalid" || text == "File format is invalid." {
            return t("notice.backupImportFormatInvalid")
        }
        if text == "Remote snapshot payload has invalid format." {
            return t("notice.backupImportFormatInvalid")
        }
        if text == "Remote data is not a supported ZeroChat encrypted snapshot." {
            return t("notice.backupImportEncryptedOnly")
        }
        if text == "Data encryption password is required." {
            return t("message.dataPasswordRequired")
        }
        if text == "Cloudflare Worker endpoint is required." ||
            text == "Cloudflare Worker URL is required." {
            return t("message.cloudflareWorkerRequired")
        }
        if Self.isCloudflareEndpointSafetyError(text) {
            return t("error.syncEndpointUnsafe")
        }
        if text == "Remote data could not be decrypted with this password." ||
            text == "Remote incremental data could not be decrypted with this password." {
            return t("error.remoteWrongPassword")
        }
        if text == "Cloud data changed. Pull again before uploading." {
            return t("error.remoteUpdated")
        }
        if Self.isRemoteSyncFormatError(text) {
            return t("error.remoteDataBadFormat")
        }
        if text.hasPrefix("Cloud incremental sync check failed:") {
            return "\(t("error.cloudIncrementalCheckFailedPrefix")): \(Self.afterColon(text))"
        }
        if Self.isCloudSyncStepFailure(text) {
            return "\(t("error.cloudSyncStepFailedPrefix")): \(Self.afterColon(text))"
        }
        if text.hasPrefix("Cloud clear failed:") {
            return "\(t("message.cloudClearFailedPrefix")): \(Self.afterColon(text))"
        }
        if text.hasPrefix("Cloud sync request failed with HTTP ") {
            let status = text
                .replacingOccurrences(of: "Cloud sync request failed with HTTP", with: "")
                .trimmingCharacters(in: CharacterSet(charactersIn: ". "))
            return "\(t("error.cloudSyncHttpFailedPrefix")) \(status)"
        }
        if let providerErrorKey = Self.providerHttpErrorKey(text) {
            return t(providerErrorKey)
        }
        return text
    }

    private static func providerHttpErrorKey(_ text: String) -> String? {
        let normalized = text.lowercased()
        let status = providerHttpStatus(normalized)

        if status == 401 ||
            status == 403 ||
            containsAny(normalized, providerAuthErrorMarkers) {
            return "error.apiKeyInvalid"
        }
        if status == 402 ||
            containsAny(normalized, providerQuotaErrorMarkers) {
            return "error.apiBalanceInsufficient"
        }
        if status == 408 ||
            status == 504 ||
            containsAny(normalized, providerTimeoutErrorMarkers) {
            return "error.networkRequestFailed"
        }
        if status == 429 ||
            containsAny(normalized, providerRateLimitErrorMarkers) {
            return "error.apiRateLimited"
        }
        if status == 404 ||
            containsAny(normalized, providerEndpointMissingMarkers) {
            return "error.providerEndpointMissing"
        }
        if status.map({ (500...599).contains($0) }) == true ||
            containsAny(normalized, providerUnavailableErrorMarkers) {
            return "error.apiUnavailable"
        }
        if containsAny(normalized, providerRequestFailureMarkers) {
            return "error.apiRequestFailed"
        }
        return nil
    }

    private static func providerHttpStatus(_ text: String) -> Int? {
        let range = NSRange(text.startIndex..<text.endIndex, in: text)
        guard let regex = providerHttpStatusRegex,
              let match = regex.firstMatch(in: text, options: [], range: range),
              match.numberOfRanges > 1,
              let statusRange = Range(match.range(at: 1), in: text) else {
            return nil
        }
        return Int(text[statusRange])
    }

    private static func containsAny(_ text: String, _ markers: [String]) -> Bool {
        markers.contains { text.contains($0) }
    }

    func syncStatusMessage(_ raw: String?) -> String {
        let text = (raw ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
        if text.isEmpty {
            return ""
        }

        switch text {
        case "Sync complete", "同步完成":
            return t("sync.status.complete")
        case "Remote data restored",
             "Remote encrypted data applied",
             "已采用远端加密数据",
             "已采用远端加密数":
            return t("sync.status.remoteAccepted")
        case "Cloud sync is waiting for the data encryption password.":
            return t("message.dataPasswordRequired")
        case "Cloud sync failed":
            return t("message.savedLocallySyncQueued")
        default:
            return errorMessage(text)
        }
    }

