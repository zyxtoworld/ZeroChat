function splitTopLevelLookaheads(pattern) {
  const lookaheads = []
  let index = 0

  while (index < pattern.length) {
    const positive = pattern.startsWith('(?=', index)
    const negative = pattern.startsWith('(?!', index)
    if (!positive && !negative) {
      return null
    }

    const bodyStart = index + 3
    let depth = 1
    let escaped = false
    let inCharacterClass = false
    let cursor = bodyStart

    for (; cursor < pattern.length; cursor += 1) {
      const character = pattern[cursor]
      if (escaped) {
        escaped = false
        continue
      }
      if (character === '\\') {
        escaped = true
        continue
      }
      if (character === '[') {
        inCharacterClass = true
        continue
      }
      if (character === ']' && inCharacterClass) {
        inCharacterClass = false
        continue
      }
      if (inCharacterClass) {
        continue
      }
      if (character === '(') {
        depth += 1
      } else if (character === ')') {
        depth -= 1
        if (depth === 0) {
          break
        }
      }
    }

    if (depth !== 0) {
      return null
    }

    lookaheads.push({ positive, body: pattern.slice(bodyStart, cursor) })
    index = cursor + 1
  }

  return lookaheads.length > 1 ? lookaheads : null
}

function testRegex(source, marker) {
  const lookaheads = splitTopLevelLookaheads(marker.source)
  if (!lookaheads) {
    return marker.test(source)
  }

  const flags = marker.flags.replace(/[gy]/g, '')
  return lookaheads.every(({ positive, body }) => {
    const matched = new RegExp(`^(?:${body})`, flags).test(source)
    return positive ? matched : !matched
  })
}

function expectMarker(source, marker, label) {
  traceNativeParityStep(label)
  const passed = Array.isArray(marker)
    ? marker.every((item) => (item instanceof RegExp ? testRegex(source, item) : source.includes(item)))
    : marker instanceof RegExp
      ? testRegex(source, marker)
      : source.includes(marker)

  if (!passed) {
    failures.push(label)
  }
}

function expectContract(source, platformName, checks) {
  for (const [label, marker] of checks) {
    expectMarker(source, marker, `${platformName}: ${label}`)
  }
}

function expectNativeProviderCatalog(source, platformName) {
  if (!['Android', 'Apple', 'Linux'].includes(platformName)) {
    return
  }

  const providerIds = new Set(
    [...source.matchAll(/provider\(\s*"([^"]+)"/g)].map((match) => match[1]),
  )
  const missing = requiredNativeProviderPresetIds.filter((id) => !providerIds.has(id))

  if (providerIds.size < 20 || missing.length > 0) {
    failures.push(
      `${platformName}: native Provider preset catalog must keep 20+ first-run presets; found ${providerIds.size}, missing ${missing.join(', ')}`,
    )
  }
}

function sortedUnique(values) {
  return Array.from(new Set(values)).sort()
}

function lastStringLiteral(line) {
  const matches = Array.from(
    line.matchAll(/(?:L)?["']([^"']+)["']/g),
    (match) => match[1],
  )

  return matches.at(-1) ?? ''
}

function extractNativeRuntimeProxyActions(source) {
  const runtimeActionLines = source
    .split(/\r?\n/)
    .filter((line) =>
      /\b(?:applyProxyHeaders|apply_proxy_headers|ApplyProxyHeaders)\s*\(/.test(line) ||
      /\b(?:action|action:)\s*[:=]\s*(?:L)?["']/.test(line) ||
      /^\s*(?:L)?["'][a-z-]+["'],?\s*$/.test(line),
    )

  return sortedUnique(
    runtimeActionLines
      .map(lastStringLiteral)
      .filter((value) => expectedNativeRuntimeProxyActions.includes(value)),
  )
}

function expectExactList(actual, expected, label) {
  const actualSet = new Set(actual)
  const expectedSet = new Set(expected)
  const missing = expected.filter((value) => !actualSet.has(value))
  const extra = actual.filter((value) => !expectedSet.has(value))

  if (missing.length || extra.length) {
    failures.push(
      `${label}: expected ${expected.join(', ')}, missing ${missing.join(', ') || 'none'}, extra ${extra.join(', ') || 'none'}`,
    )
  }
}

async function expectNativeRuntimeProxyActionCoverage() {
  for (const [index, [platformName, file]] of nativeRuntimeProxyActionFiles.entries()) {
    try {
      const source = await readFile(file, 'utf8')
      const actions = extractNativeRuntimeProxyActions(source)

      expectExactList(
        actions,
        expectedNativeRuntimeProxyActions,
        nativeRuntimeProxyActionCoverageLabels[index] ?? `${platformName}: native runtime proxy action coverage`,
      )
    } catch (error) {
      failures.push(`${platformName}: missing native runtime proxy action file ${file}: ${error.message}`)
    }
  }
}

function androidKotlinAuditView(source, file) {
  if (!file.startsWith('apps/android/') || !file.endsWith('.kt')) {
    return source
  }

  const legacyInternalMarkers = source
    .split(/\r?\n/)
    .filter((line) =>
      /^(suspend fun|fun|data class|sealed class|enum class|const val|class)\s/.test(line),
    )
    .map((line) => {
      const marker = `internal ${line}`
      return marker.replace(' constructor(', ' internal constructor(')
    })

  if (
    (file.endsWith('ChatTopBar.kt') || file.endsWith('SettingsScreen.kt')) &&
    source.includes('R.drawable.ic_launcher_foreground')
  ) {
    legacyInternalMarkers.push(
      file.endsWith('SettingsScreen.kt')
        ? 'ZeroChatAppIcon(modifier = Modifier.size(38.dp))'
        : 'ZeroChatAppIcon(modifier = Modifier.size(32.dp))',
    )
  }

  return legacyInternalMarkers.length
    ? `${source}\n${legacyInternalMarkers.join('\n')}`
    : source
}

async function readPlatform(platform) {
  const parts = []

  for (const file of platform.files) {
    try {
      parts.push(androidKotlinAuditView(await readFile(file, 'utf8'), file))
    } catch (error) {
      failures.push(`${platform.name}: missing ${file}: ${error.message}`)
    }
  }

  return parts.join('\n')
}

