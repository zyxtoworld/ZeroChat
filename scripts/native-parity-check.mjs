for (const platform of platforms) {
  traceNativeParityStep(`${platform.name}: read platform source`)
  const source = await readPlatform(platform)
  const normalized = source.toLowerCase()

  for (const check of platform.checks) {
    traceNativeParityStep(`${platform.name}: marker ${check}`)
    if (!normalized.includes(check.toLowerCase())) {
      failures.push(`${platform.name}: missing parity marker ${check}`)
    }
  }

  expectContract(source, platform.name, contracts[platform.name] ?? [])
  expectNativeProviderCatalog(source, platform.name)

  if (platform.name === 'Linux') {
    for (const staleSkillHandoff of [
      'message.skillsNativePending',
      'Edit Skills in Web/PWA until this native screen is verified',
    ]) {
      if (source.includes(staleSkillHandoff)) {
        failures.push(
          `Linux: Skill management is source-wired, so stale Web/PWA handoff copy must not remain: ${staleSkillHandoff}`,
        )
      }
    }

    const alwaysVisibleMessageActions = `let actions = gtk::Box::new(gtk::Orientation::Horizontal, row_spacing(compact));
    let mut has_actions = false;`
    if (source.includes(alwaysVisibleMessageActions)) {
      failures.push(
        'Linux: message actions must stay in the GtkPopoverMenu, not an always-visible button row.',
      )
    }

    if (source.includes('gtk::MessageDialog::builder()')) {
      failures.push(
        'Linux: destructive confirmations must stay on AdwMessageDialog instead of legacy gtk::MessageDialog.',
      )
    }
  }

  if (platform.name === 'Apple') {
    const alwaysVisibleMessageActionRow = `HStack {
                    if message.role == .user {
                        Button(i18n.t("action.editResend"), action: edit)
                    } else {
                        Button(i18n.t("action.regenerate"), action: regenerate)
                    }
                    Button(i18n.t("action.delete"), role: .destructive, action: delete)
                }
                .font(.caption)`
    if (source.includes(alwaysVisibleMessageActionRow)) {
      failures.push(
        'Apple: message actions must stay in the native context menu, not an always-visible button row.',
      )
    }
  }
}

