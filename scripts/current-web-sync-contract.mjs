export function findCurrentWebSyncContractFailures(sources) {
  const failures = []
  for (const [sourceName, markers] of Object.entries(
    currentWebSyncContractMarkers,
  )) {
    const source = String(sources?.[sourceName] ?? '')
    for (const marker of markers) {
      if (!source.includes(marker)) {
        failures.push(`${sourceName} is missing: ${marker}`)
      }
    }
  }
  return failures
}

export function assertCurrentWebSyncContract(
  sources,
  checkId = CURRENT_WEB_SYNC_CONTRACT_CHECK_ID,
) {
  const failures = findCurrentWebSyncContractFailures(sources)
  if (failures.length > 0) {
    throw new Error(
      `${checkId} failed:\n- ${failures.join('\n- ')}`,
    )
  }
  return { checkId }
}
