export function findCurrentWebAppShellMarkerFailures(
  sources,
  requiredMarkers = currentWebAppShellContractMarkers,
  forbiddenMarkers = currentWebAppShellForbiddenMarkers,
) {
  const failures = []
  for (const [sourceName, markers] of Object.entries(requiredMarkers)) {
    const source = String(sources?.[sourceName] ?? '')
    for (const marker of markers) {
      if (!source.includes(marker)) failures.push(`${sourceName} is missing: ${marker}`)
    }
  }
  for (const [sourceName, markers] of Object.entries(forbiddenMarkers)) {
    const source = String(sources?.[sourceName] ?? '')
    for (const marker of markers) {
      if (source.includes(marker)) failures.push(`${sourceName} contains retired authority: ${marker}`)
    }
  }
  return failures
}

export function findCurrentWebAppShellContractFailures(sources) {
  const failures = findCurrentWebAppShellMarkerFailures(sources)
  const sharedSecretInputCount =
    String(sources?.settingsViewSource ?? '').match(/<SecretInput\b/gu)?.length ?? 0
  if (sharedSecretInputCount !== 3) {
    failures.push(
      `settingsViewSource must render exactly three shared SecretInput fields, found ${sharedSecretInputCount}`,
    )
  }
  const appStoreSource = String(sources?.appStoreSource ?? '')
  const staleSkillMutationCleanup =
    /if \(revision !== dataRevision \|\| get\(\)\.data !== current\) \{\n {8}queueNewSkillContentRefs\(current, persisted\)\n {8}await cleanupPendingSkillContentRefs\(\)\n {8}continue/u.test(
      appStoreSource,
    )
  if (!staleSkillMutationCleanup) {
    failures.push(
      'appStoreSource must queue and clean newly materialized Skill refs before retrying a stale mutation',
    )
  }
  const appShellSource = String(sources?.appShellSource ?? '')
  const migrationFeedbackInstallIndex = appShellSource.indexOf(
    'installLocalEncryptionMigrationFeedback({',
  )
  const initializationIndex = appShellSource.indexOf(
    'void useAppStore.getState().init()',
  )
  if (
    migrationFeedbackInstallIndex !== -1 &&
    initializationIndex !== -1 &&
    migrationFeedbackInstallIndex > initializationIndex
  ) {
    failures.push(
      'appShellSource must install local encryption migration feedback before initialization',
    )
  }
  return failures
}

export function assertCurrentWebAppShellContract(
  sources,
  checkId = CURRENT_WEB_APP_SHELL_CONTRACT_CHECK_ID,
) {
  const failures = findCurrentWebAppShellContractFailures(sources)
  if (failures.length > 0) {
    throw new Error(`${checkId} failed:\n- ${failures.join('\n- ')}`)
  }
  return { checkId }
}
