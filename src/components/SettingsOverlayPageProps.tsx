import type { MouseEvent as ReactMouseEvent } from 'react'

import { timeLabel } from '../services/uiRuntime'
import { runLeafAction } from './MessageActionBoundary'
import { TargetNotice } from './Notice'
import type {
  SettingsNoticeTarget,
  SettingsPageProps,
} from './SettingsPageTypes'
import type { SettingsOverlayProps } from './SettingsOverlayTypes'

interface SettingsOverlayPageHandlers {
  onCloseSettings: (
    event: ReactMouseEvent<HTMLButtonElement>,
  ) => void
  onSelectModelProvider: (providerId: string) => void
  onSelectProvider: (providerId: string) => void
}

export function settingsPagePropsFromOverlay(
  props: SettingsOverlayProps,
  handlers: SettingsOverlayPageHandlers,
): SettingsPageProps {
  const {
    chatContextMessageLimit,
    checkingProviderId,
    cloudflareAccessKey,
    currentNotice,
    data,
    editingModelDraft,
    editingModelProviderId,
    editingModelSource,
    editingSkillId,
    githubTokenValue,
    guideState,
    hasMoreRenderedSkills,
    loadingModelsProviderId,
    modelDraft,
    modelDraftProviderId,
    providerConnectivityResults,
    providerKeys,
    renderedSkillLimit,
    renderedSkills,
    selectedProvider,
    settingsModalRef,
    settingsTab,
    skillCount,
    skillDraftContent,
    skillDraftName,
    skillEditContent,
    skillEditLoading,
    skillEditName,
    skillEditSaving,
    skillImporting,
    skillMutationPending,
    skillListMoreRef,
    syncChrome,
    syncConfigRef,
    syncPassphraseValue,
    syncing,
    settingsDataPending,
    systemDateLocales,
    t,
    visibleProviders,
    addProviderFromPresetSelect,
    addSkillFromDraft,
    beginEditProviderModel,
    cancelEditingSkill,
    changeChatContextMessageLimit,
    changeLanguage,
    changeSyncMode,
    changeTheme,
    checkProviderCapability,
    checkProviderFullCapabilities,
    checkProviderConnectivity,
    checkSelectedModel,
    clearCloudData,
    clearModelRenameDraft,
    commitEditsOnBlur,
    commitModelDraft,
    commitProviderModelRename,
    commitSyncPassphraseOnBlur,
    copyCloudflareAccessKey,
    deleteSkill,
    exportData,
    handleModelDraftChange,
    handleModelDraftKeyDown,
    handleModelDragStart,
    handleModelDrop,
    handleModelRenameKeyDown,
    handleProviderDragStart,
    handleProviderDrop,
    importData,
    importSkillFiles,
    openFirstProviderSetup,
    openGuide,
    refreshProviderModels,
    moveProvider,
    moveProviderModel,
    removeProvider,
    removeProviderModel,
    renderFeatureHint,
    renderSecretInput,
    resetLocalData,
    runSync,
    saveEditingSkill,
    selectProviderAudioSpeechModel,
    selectProviderAudioTranscriptionModel,
    selectProviderEmbeddingModel,
    selectProviderImageModel,
    selectProviderModerationModel,
    selectProviderModel,
    selectProviderRealtimeModel,
    onCompactModeChange,
    onResetSyncPassphrase,
    onSelectTab,
    setEditingModelDraft,
    setProviderEnabled,
    setSkillDraftContent,
    setSkillDraftName,
    setSkillEditContent,
    setSkillEditName,
    showMoreSkills,
    startEditingSkill,
    updateGithubTokenSecret,
    updateProvider,
    updateProviderKey,
    updateSkill,
    updateSkillSettings,
    updateSyncAutoSync,
    updateSyncGistFile,
    updateSyncGistId,
    updateSyncPassphraseDraft,
    updateSyncWorkerEndpoint,
  } = props

  const { onCloseSettings, onSelectModelProvider, onSelectProvider } = handlers
  const renderTargetNotice = (
    target: SettingsNoticeTarget,
    variant?: 'field',
  ) => (
    <TargetNotice
      notice={currentNotice}
      targets={[target]}
      variant={variant}
    />
  )

  return {
    chatContextMessageLimit,
    checkingProviderId,
    cloudflareAccessKey,
    data,
    editingModelDraft,
    editingModelProviderId,
    editingModelSource,
    editingSkillId,
    githubTokenValue,
    hasMoreRenderedSkills,
    loadingModelsProviderId,
    modelDraft,
    modelDraftProviderId,
    providerConnectivityResults,
    providerKeys,
    recentSyncText: t('sync.recent', {
      time: timeLabel(
        data.sync.lastSyncAt,
        systemDateLocales,
        t('time.neverSynced'),
      ),
    }),
    renderedSkillLimit,
    renderedSkills,
    selectedProvider,
    selectedProviderAudioSpeechModels:
      guideState.selectedProviderAudioSpeechModels,
    selectedProviderAudioTranscriptionModels:
      guideState.selectedProviderAudioTranscriptionModels,
    selectedProviderChatModels: guideState.selectedProviderChatModels,
    selectedProviderEmbeddingModels: guideState.selectedProviderEmbeddingModels,
    selectedProviderImageModels: guideState.selectedProviderImageModels,
    selectedProviderModerationModels:
      guideState.selectedProviderModerationModels,
    selectedProviderModels: guideState.selectedProviderModels,
    selectedProviderRealtimeModels: guideState.selectedProviderRealtimeModels,
    settingsModalRef,
    settingsTab,
    skillCount,
    skillDraftContent,
    skillDraftName,
    skillEditContent,
    skillEditLoading,
    skillEditName,
    skillEditSaving,
    skillImporting,
    skillMutationPending,
    skillListMoreRef,
    systemDateLocales,
    syncConfigRef,
    syncModeLabel: syncChrome.modeLabel,
    syncPassphraseValue,
    syncRequirement: syncChrome.requirement,
    syncStatusText: syncChrome.statusText,
    syncing,
    settingsDataPending,
    t,
    visibleProviders,
    renderFeatureHint,
    renderFieldNotice: (target) => renderTargetNotice(target, 'field'),
    renderNotice: renderTargetNotice,
    renderSecretInput,
    onAddProviderFromPreset: addProviderFromPresetSelect,
    onAddSkillFromDraft: addSkillFromDraft,
    onBeginEditProviderModel: beginEditProviderModel,
    onCancelEditingSkill: cancelEditingSkill,
    onChangeChatContextMessageLimit: changeChatContextMessageLimit,
    onChangeSyncMode: changeSyncMode,
    onCheckModel: checkSelectedModel,
    onCheckProviderCapability: checkProviderCapability,
    onCheckProviderFullCapabilities: checkProviderFullCapabilities,
    onCheckProviderConnectivity: checkProviderConnectivity,
    onClearCloudData: () => runLeafAction(clearCloudData),
    onClearModelRenameDraft: clearModelRenameDraft,
    onCloseSettings,
    onCommitEditsOnBlur: commitEditsOnBlur,
    onCommitModelDraft: commitModelDraft,
    onCommitProviderModelRename: commitProviderModelRename,
    onCopyCloudflareAccessKey: () =>
      runLeafAction(copyCloudflareAccessKey, cloudflareAccessKey),
    onDeleteSkill: deleteSkill,
    onEditingModelDraftChange: setEditingModelDraft,
    onExportData: () => runLeafAction(exportData),
    onAutoSyncChange: updateSyncAutoSync,
    onGithubTokenChange: updateGithubTokenSecret,
    onGistFileChange: updateSyncGistFile,
    onGistIdChange: updateSyncGistId,
    onImportData: (event) => runLeafAction(importData, event),
    onImportSkillFiles: importSkillFiles,
    onModelDraftChange: handleModelDraftChange,
    onModelDraftKeyDown: handleModelDraftKeyDown,
    onModelDragStart: handleModelDragStart,
    onModelDrop: handleModelDrop,
    onMoveProviderModel: moveProviderModel,
    onModelRenameKeyDown: handleModelRenameKeyDown,
    onOpenFirstProviderSetup: openFirstProviderSetup,
    onOpenGuide: openGuide,
    onProviderDragStart: handleProviderDragStart,
    onProviderDrop: handleProviderDrop,
    onMoveProvider: moveProvider,
    onRefreshModels: refreshProviderModels,
    onRemoveProvider: removeProvider,
    onRemoveProviderModel: removeProviderModel,
    onResetLocalData: () => runLeafAction(resetLocalData),
    onResetSyncPassphrase,
    onRunSync: () => runLeafAction(runSync),
    onSaveEditingSkill: saveEditingSkill,
    onSelectAudioSpeechModel: selectProviderAudioSpeechModel,
    onSelectAudioTranscriptionModel: selectProviderAudioTranscriptionModel,
    onSelectChatModel: selectProviderModel,
    onSelectEmbeddingModel: selectProviderEmbeddingModel,
    onSelectImageModel: selectProviderImageModel,
    onSelectModerationModel: selectProviderModerationModel,
    onSelectModelProvider,
    onSelectProvider,
    onSelectRealtimeModel: selectProviderRealtimeModel,
    onSelectTab,
    onSetProviderEnabled: setProviderEnabled,
    onShowMoreSkills: showMoreSkills,
    onSkillDraftContentChange: setSkillDraftContent,
    onSkillDraftNameChange: setSkillDraftName,
    onSkillEditContentChange: setSkillEditContent,
    onSkillEditNameChange: setSkillEditName,
    onStartEditingSkill: startEditingSkill,
    onSyncPassphraseBlur: () => runLeafAction(commitSyncPassphraseOnBlur),
    onSyncPassphraseChange: updateSyncPassphraseDraft,
    onThemeChange: changeTheme,
    onLanguageChange: changeLanguage,
    onCompactModeChange,
    onUpdateProvider: updateProvider,
    onUpdateProviderKey: updateProviderKey,
    onUpdateSkill: updateSkill,
    onUpdateSkillSettings: updateSkillSettings,
    onWorkerEndpointChange: updateSyncWorkerEndpoint,
  }
}
