export function providerFromPreset(preset: ProviderPreset): ProviderConfig {
  const now = Date.now()

  return {
    id: crypto.randomUUID(),
    name: preset.name,
    kind: preset.kind,
    baseUrl: preset.baseUrl,
    model: preset.model,
    enabled: true,
    needsApiKey: preset.needsApiKey,
    createdAt: now,
    updatedAt: now,
  }
}
